#!/usr/bin/env node
/**
 * Merge local secrets into dashboard/.dev.vars (and optionally worker .dev.vars).
 *
 * Token precedence for INGESTION_TRIGGER_TOKEN (dashboard → production Worker):
 *   1. INGESTION_TRIGGER_TOKEN env
 *   2. workers/fantasy402-ingestion/.archive-auth-token
 *   3. workers/fantasy402-ingestion/.dev.vars
 *   4. 1Password (op) when available
 *
 * Usage:
 *   node scripts/sync-dev-vars.mjs           # write dashboard/.dev.vars
 *   node scripts/sync-dev-vars.mjs --check   # validate only, exit 1 if missing
 *   node scripts/sync-dev-vars.mjs --worker  # also merge FANTASY402_* into worker .dev.vars
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { execSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DASHBOARD_ROOT = path.resolve(__dirname, "..");
const REPO_ROOT = path.resolve(DASHBOARD_ROOT, "..");
const WORKER_ROOT = path.join(REPO_ROOT, "workers", "fantasy402-ingestion");

const DASHBOARD_DEV_VARS = path.join(DASHBOARD_ROOT, ".dev.vars");
const WORKER_DEV_VARS = path.join(WORKER_ROOT, ".dev.vars");
const ROOT_DEV_VARS = path.join(REPO_ROOT, ".dev.vars");
const ARCHIVE_TOKEN = path.join(WORKER_ROOT, ".archive-auth-token");
const EXAMPLE = path.join(DASHBOARD_ROOT, ".dev.vars.example");

const DEFAULT_WORKER_UPSTREAM = "https://fantasy402-ingestion.utahj4754.workers.dev";
const LOCAL_WORKER_UPSTREAM = "http://127.0.0.1:8789";

const DASHBOARD_REQUIRED = ["INGESTION_TRIGGER_TOKEN"];
const SHARED_OPTIONAL = [
  "FANTASY402_USERNAME",
  "FANTASY402_PASSWORD",
  "FANTASY402_AGENT_ID",
  "FANTASY402_CUSTOMER_ID",
];

const args = new Set(process.argv.slice(2));
const checkOnly = args.has("--check");
const syncWorker = args.has("--worker");
const useLocalWorker = args.has("--local-worker");

function parseDevVars(filePath) {
  if (!existsSync(filePath)) return {};
  const out = {};
  for (const line of readFileSync(filePath, "utf8").split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq <= 0) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

function readTrimmedFile(filePath) {
  if (!existsSync(filePath)) return "";
  return readFileSync(filePath, "utf8").trim();
}

function tryOpToken() {
  try {
    execSync("command -v op", { stdio: "ignore" });
    return execSync(
      'op item get "Fantasy402 Worker" --vault=DEV --field=INGESTION_TRIGGER_TOKEN --reveal',
      { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] },
    ).trim();
  } catch {
    return "";
  }
}

function resolveIngestionToken(env = {}) {
  if (process.env.INGESTION_TRIGGER_TOKEN?.trim()) {
    return process.env.INGESTION_TRIGGER_TOKEN.trim();
  }
  const archive = readTrimmedFile(ARCHIVE_TOKEN);
  if (archive) return archive;
  if (env.INGESTION_TRIGGER_TOKEN?.trim()) return env.INGESTION_TRIGGER_TOKEN.trim();
  const fromOp = tryOpToken();
  if (fromOp) return fromOp;
  return "";
}

function serializeDevVars(map) {
  const keys = Object.keys(map).sort((a, b) => {
    const order = [
      "FANTASY402_WORKER_UPSTREAM",
      "WORKER_ORIGIN",
      "INGESTION_TRIGGER_TOKEN",
      ...SHARED_OPTIONAL,
    ];
    const ai = order.indexOf(a);
    const bi = order.indexOf(b);
    if (ai !== -1 || bi !== -1) return (ai === -1 ? 999 : ai) - (bi === -1 ? 999 : bi);
    return a.localeCompare(b);
  });
  const lines = [
    "# Generated by dashboard/scripts/sync-dev-vars.mjs — do not commit (.gitignore)",
    `# ${new Date().toISOString()}`,
    "",
  ];
  for (const key of keys) {
    const value = map[key];
    if (value == null || value === "") continue;
    const safe = String(value).includes("\n") ? JSON.stringify(value) : String(value);
    lines.push(`${key}=${safe}`);
  }
  lines.push("");
  return lines.join("\n");
}

function missingKeys(map, required) {
  return required.filter((k) => !map[k]?.trim());
}

function buildDashboardVars() {
  const root = parseDevVars(ROOT_DEV_VARS);
  const worker = parseDevVars(WORKER_DEV_VARS);
  const merged = { ...root, ...worker };

  const token = useLocalWorker
    ? worker.INGESTION_TRIGGER_TOKEN?.trim() || "dev-token-replace-me"
    : resolveIngestionToken(merged);

  const upstream = useLocalWorker
    ? process.env.DASHBOARD_WORKER_UPSTREAM?.trim() || LOCAL_WORKER_UPSTREAM
    : process.env.DASHBOARD_WORKER_UPSTREAM?.trim() ||
      process.env.FANTASY402_WORKER_UPSTREAM?.trim() ||
      process.env.WORKER_ORIGIN?.trim() ||
      DEFAULT_WORKER_UPSTREAM;

  const out = {
    FANTASY402_WORKER_UPSTREAM: upstream,
    INGESTION_TRIGGER_TOKEN: token,
    ...Object.fromEntries(
      SHARED_OPTIONAL.map((k) => [k, merged[k]?.trim() || ""]).filter(([, v]) => v),
    ),
  };
  return out;
}

function buildWorkerVars() {
  const root = parseDevVars(ROOT_DEV_VARS);
  const worker = parseDevVars(WORKER_DEV_VARS);
  const token =
    worker.INGESTION_TRIGGER_TOKEN?.trim() ||
    (useLocalWorker ? "dev-token-replace-me" : resolveIngestionToken({ ...root, ...worker }));
  return {
    INGESTION_TRIGGER_TOKEN: token,
    ...Object.fromEntries(
      SHARED_OPTIONAL.map((k) => [k, (worker[k] || root[k] || "").trim()]).filter(([, v]) => v),
    ),
  };
}

const dashboardVars = buildDashboardVars();
const dashMissing = missingKeys(dashboardVars, DASHBOARD_REQUIRED);

if (dashMissing.length) {
  console.error("Missing required dashboard secrets:", dashMissing.join(", "));
  console.error("Fix: create workers/fantasy402-ingestion/.archive-auth-token or set INGESTION_TRIGGER_TOKEN");
  process.exit(1);
}

const optionalMissing = SHARED_OPTIONAL.filter((k) => !dashboardVars[k]?.trim());
if (optionalMissing.length) {
  console.warn("Optional (ingest/auth scripts):", optionalMissing.join(", "));
}

if (checkOnly) {
  console.log("dashboard/.dev.vars OK —", DASHBOARD_REQUIRED.join(", "));
  if (optionalMissing.length) console.log("optional missing:", optionalMissing.join(", "));
  process.exit(0);
}

writeFileSync(DASHBOARD_DEV_VARS, serializeDevVars(dashboardVars), "utf8");
console.log("Wrote", DASHBOARD_DEV_VARS);
console.log("  FANTASY402_WORKER_UPSTREAM =", dashboardVars.FANTASY402_WORKER_UPSTREAM);
console.log("  INGESTION_TRIGGER_TOKEN    =", `(${dashboardVars.INGESTION_TRIGGER_TOKEN.length} chars)`);

if (syncWorker) {
  const workerPayload = buildWorkerVars();
  writeFileSync(WORKER_DEV_VARS, serializeDevVars(workerPayload), "utf8");
  console.log("Wrote", WORKER_DEV_VARS);
}

if (!existsSync(EXAMPLE)) {
  writeFileSync(
    EXAMPLE,
    serializeDevVars({
      FANTASY402_WORKER_UPSTREAM: DEFAULT_WORKER_UPSTREAM,
      INGESTION_TRIGGER_TOKEN: "your-ingestion-trigger-token",
      FANTASY402_USERNAME: "your-customer-id",
      FANTASY402_PASSWORD: "your-password",
      FANTASY402_AGENT_ID: "your-agent-id",
      FANTASY402_CUSTOMER_ID: "optional-player-customer-id",
    }),
    "utf8",
  );
}
