function enhanceSpec(spec) {
  enhanceInfo(spec);
  ensureProblemDetails(spec);
  ensureExamples(spec);
  for (const [apiPath, pathItem] of Object.entries(spec.paths || {})) {
    for (const operation of Object.values(pathItem || {})) {
      if (!isObject(operation)) continue;
      enhanceErrorResponses(operation);
      enhanceDeprecatedOperation(operation, apiPath);
    }
  }
}

const results = [];
for (const relativeSpecPath of specPaths) {
  const jsonPath = path.resolve(root, relativeSpecPath);
  if (!fs.existsSync(jsonPath)) continue;
  const spec = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
  enhanceSpec(spec);
  fs.writeFileSync(jsonPath, `${JSON.stringify(spec, null, 2)}\n`);

  const yamlPath = jsonPath.replace(/\.json$/, '.yaml');
  if (fs.existsSync(yamlPath)) {
    fs.writeFileSync(yamlPath, `${toYaml(spec)}\n`);
  }

  results.push(path.relative(root, jsonPath));
}

console.log(JSON.stringify({
  status: 'ok',
  improved: results,
}, null, 2));
