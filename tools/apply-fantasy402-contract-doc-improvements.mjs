#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { toYaml } from './yaml.mjs';

const root = process.cwd();
const defaultSpecs = [
  '.o11y/fantasy402-redacted-deep/api-spec-secured/openapi.secured.json',
  '.o11y/fantasy402-redacted-deep/api-spec-secured/openapi.secured.slim.json',
  '.o11y/fantasy402-redacted-deep/api-spec-secured/openapi.secured.examples.json',
];
const specPaths = process.argv.slice(2).length ? process.argv.slice(2) : defaultSpecs;

function isObject(value) {
  return value && typeof value === 'object' && !Array.isArray(value);
}

function ensureProblemDetails(spec) {
  spec.components ||= {};
  spec.components.schemas ||= {};
  spec.components.examples ||= {};

  spec.components.schemas.ProblemDetails = {
    type: 'object',
    additionalProperties: true,
    description: 'RFC 9457 problem detail object for machine-readable API errors.',
    properties: {
      type: {
        type: 'string',
        format: 'uri-reference',
        description: 'Stable problem type URI. Use about:blank only for generic errors.',
      },
      title: {
        type: 'string',
        description: 'Short, human-readable error summary.',
      },
      status: {
        type: 'integer',
        minimum: 100,
        maximum: 599,
        description: 'HTTP status code generated by the origin server.',
      },
      detail: {
        type: 'string',
        description: 'Human-readable detail specific to this occurrence.',
      },
      instance: {
        type: 'string',
        format: 'uri-reference',
        description: 'Request path or trace URI for this occurrence.',
      },
      retryAfter: {
        type: 'integer',
        minimum: 0,
        description: 'Retry delay in seconds when the error is recoverable.',
      },
      rateLimit: {
        type: 'object',
        additionalProperties: false,
        properties: {
          limit: { type: 'integer', minimum: 0 },
          remaining: { type: 'integer', minimum: 0 },
          reset: {
            type: 'integer',
            minimum: 0,
            description: 'Unix timestamp when the current rate-limit window resets.',
          },
        },
      },
    },
    required: ['type', 'title', 'status'],
  };

  spec.components.examples.RateLimitProblem = {
    summary: 'Rate limit exceeded',
    value: {
      type: 'https://fantasy402.com/errors/rate-limit-exceeded',
      title: 'Rate Limit Exceeded',
      status: 429,
      detail: 'Request budget for this operation was exhausted. Retry after the indicated delay.',
      instance: '/cloud/api/Manager/getBetTicker',
      retryAfter: 47,
      rateLimit: {
        limit: 30,
        remaining: 0,
        reset: 1779026447,
      },
    },
  };

  spec.components.examples.GenericProblem = {
    summary: 'Generic API error',
    value: {
      type: 'about:blank',
      title: 'API Error',
      status: 400,
      detail: 'The request could not be processed.',
      instance: '/cloud/api/Manager/getPlayers',
    },
  };
}

function ensureHeader(response, name, header) {
  response.headers ||= {};
  response.headers[name] = {
    ...(response.headers[name] || {}),
    ...header,
  };
}

function ensureProblemContent(response, status) {
  response.content ||= {};
  response.content['application/problem+json'] ||= {
    schema: { $ref: '#/components/schemas/ProblemDetails' },
  };
  response.content['application/problem+json'].schema ||= { $ref: '#/components/schemas/ProblemDetails' };
  response.content['application/problem+json'].examples ||= {};
  response.content['application/problem+json'].examples[status === '429' ? 'tooManyRequests' : 'problem'] = {
    $ref: status === '429' ? '#/components/examples/RateLimitProblem' : '#/components/examples/GenericProblem',
  };
}

function enhanceErrorResponses(operation) {
  for (const [status, response] of Object.entries(operation.responses || {})) {
    if (!/^[45]\d\d$/.test(status) || !isObject(response)) continue;
    ensureProblemContent(response, status);
    if (status === '429') {
      ensureHeader(response, 'Retry-After', {
        schema: { type: 'integer', minimum: 0 },
        description: 'Seconds to wait before retrying the request.',
      });
    }
  }
}

function enhanceDeprecatedOperation(operation, apiPath) {
  if (operation.deprecated !== true) return;
  const sunset = apiPath.includes('getWebLog') ? '2026-06-30T00:00:00Z' : '2026-06-30T00:00:00Z';
  const isTicketPrint = apiPath.includes('getTicketDetailPrint');
  const migrationTarget = isTicketPrint ? '/cloud/api/Report/getPendingByTicket' : null;
  operation['x-sunset'] = sunset;
  operation['x-migration-target'] = migrationTarget;
  operation['x-migration-guidance'] = isTicketPrint
    ? 'Likely replacement is ticket detail lookup through getPendingByTicket, with getWagerDetailTransaction or Manager/getWagaerDetailShort as supporting read-only detail views. Confirm exact print-specific replacement before removing manual-review status.'
    : 'No like-for-like replacement has been observed. Treat 410 Gone as authoritative and keep this blocked until a narrowed audit-log endpoint is captured.';
  if (isTicketPrint) {
    operation['x-replacement-candidates'] ||= [
      '/cloud/api/Report/getPendingByTicket',
      '/cloud/api/Report/getWagerDetailTransaction',
      '/cloud/api/Manager/getWagaerDetailShort',
    ];
  }
  operation.externalDocs ||= {
    description: 'Deprecation and migration guidance.',
    url: './remediation-closeout.md',
  };

  for (const response of Object.values(operation.responses || {})) {
    if (!isObject(response)) continue;
    ensureHeader(response, 'Deprecation', {
      schema: { type: 'string' },
      description: 'HTTP deprecation signal. Value is true while this observed endpoint remains deprecated.',
    });
    ensureHeader(response, 'Sunset', {
      schema: { type: 'string', format: 'date-time' },
      description: 'Planned sunset timestamp for this deprecated observed endpoint.',
    });
    ensureHeader(response, 'Link', {
      schema: { type: 'string' },
      description: 'Migration guidance link with rel="deprecation".',
    });
  }
}

function enhanceInfo(spec) {
  spec.info ||= {};
  spec.info.title = 'Fantasy402 API (Secured Observed Contract)';
  spec.info.version = '2026-05-17-slim-v1.2';
  spec.info.contact = {
    name: 'BILLY666 / Sports Terminal',
    url: 'https://factory-wager.com',
  };
  spec.info['x-api-state'] = 'observed';
  spec.info['x-last-captured'] = '2026-05-08';
  spec.info['x-next-review'] = '2026-06-08';
  spec.info['x-ai-discovery'] = {
    llmsTxt: './llms.txt',
    stableJson: './openapi.json',
    stableYaml: './openapi.yaml',
  };
}

function enhanceSpec(spec) {
  enhanceInfo(spec);
  ensureProblemDetails(spec);
  for (const [apiPath, pathItem] of Object.entries(spec.paths || {})) {
    for (const operation of Object.values(pathItem || {})) {
      if (!isObject(operation)) continue;
      enhanceErrorResponses(operation);
      enhanceDeprecatedOperation(operation, apiPath);
    }
  }
}

const results = [];
for (const relativeSpecPath of specPaths) {
  const jsonPath = path.resolve(root, relativeSpecPath);
  if (!fs.existsSync(jsonPath)) continue;
  const spec = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
  enhanceSpec(spec);
  fs.writeFileSync(jsonPath, `${JSON.stringify(spec, null, 2)}\n`);

  const yamlPath = jsonPath.replace(/\.json$/, '.yaml');
  if (fs.existsSync(yamlPath)) {
    fs.writeFileSync(yamlPath, `${toYaml(spec)}\n`);
  }

  results.push(path.relative(root, jsonPath));
}

console.log(JSON.stringify({
  status: 'ok',
  improved: results,
}, null, 2));
