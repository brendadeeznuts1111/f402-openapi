#!/usr/bin/env node
/**
 * Regenerate harness snapshots after intentional schema/OpenAPI changes.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as dashboardSchemas from '../js/lib/schemas.js';
import {
  fingerprintOpenApiSchemas,
  fingerprintSchemaMap,
} from '../harness/zod-shape.js';
import { writeSnapshot, snapshotsDir } from '../harness/snapshot-store.js';
import {
  worstBenchmarkSchemaParse,
  writePerformanceBaseline,
  benchmarkNavigationConfig,
} from '../harness/performance-benchmark.js';
import {
  serializeNavigationSnapshot,
  SIDEBAR_CONFIG,
  sidebarConfigSchema,
} from '../js/lib/navigation-config.js';
import { readOpenApiWorkerSpec } from '../harness/verify.js';
import {
  pendingWagersQuerySchema,
  searchCustomersQuerySchema,
  transactionsLiveQuerySchema,
  agentPerformanceLiveQuerySchema,
  customerProfileQuerySchema,
  customerProfileSeedSchema,
  chartAggregatesSchema,
  localIngestSchema,
  updateCookiesSchema,
} from '../../tools/lib/f402-schemas.mjs';

const scriptDir = dirname(fileURLToPath(import.meta.url));

const workerBindingSchemas = {
  searchCustomersQuerySchema,
  pendingWagersQuerySchema,
  transactionsLiveQuerySchema,
  agentPerformanceLiveQuerySchema,
  customerProfileQuerySchema,
  customerProfileSeedSchema,
  chartAggregatesSchema,
  localIngestSchema,
  updateCookiesSchema,
};

const openApi = readOpenApiWorkerSpec();
writeSnapshot('openapi-schemas', fingerprintOpenApiSchemas(openApi));
writeSnapshot('dashboard-zod-schemas', fingerprintSchemaMap(dashboardSchemas));
writeSnapshot('worker-zod-schemas', fingerprintSchemaMap(workerBindingSchemas));
writeSnapshot('navigation-config', serializeNavigationSnapshot());

const readme = join(snapshotsDir, 'README.md');
writeFileSync(
  readme,
  `# Harness snapshots

Generated by \`npm run test:harness:update\` from \`dashboard/scripts/harness-update-snapshots.mjs\`.

Do not hand-edit. Re-run the update script when Zod or OpenAPI shapes change intentionally.
`,
  'utf8',
);

const perf = {
  'dashboard.searchCustomersQuerySchema': worstBenchmarkSchemaParse(
    dashboardSchemas.searchCustomersQuerySchema,
    { q: 'GX195', limit: 25 },
  ),
  'dashboard.pendingWagersFiltersSchema': worstBenchmarkSchemaParse(
    dashboardSchemas.pendingWagersFiltersSchema,
    { date: '2026-05-17', customer_id: '0' },
  ),
  'dashboard.transactionsLiveFiltersSchema': worstBenchmarkSchemaParse(
    dashboardSchemas.transactionsLiveFiltersSchema,
    { type: 'player', start_date: '2026-05-01', end_date: '2026-05-17' },
  ),
  'dashboard.customerNavSchema': worstBenchmarkSchemaParse(dashboardSchemas.customerNavSchema, {
    customerId: 'GX195',
  }),
  'worker.searchCustomersQuerySchema': worstBenchmarkSchemaParse(searchCustomersQuerySchema, {
    q: 'GX195',
    limit: '25',
  }),
  'worker.pendingWagersQuerySchema': worstBenchmarkSchemaParse(pendingWagersQuerySchema, {
    date: '2026-05-17',
    limit: '50',
  }),
  'navigation.validateSidebarConfig': benchmarkNavigationConfig(
    sidebarConfigSchema,
    SIDEBAR_CONFIG,
    500,
  ),
};
const perfOut = {};
for (const [k, v] of Object.entries(perf)) {
  perfOut[k] = { msPerOp: v.msPerOp, iterations: v.iterations };
}
writePerformanceBaseline(perfOut);

console.log('Updated snapshots in', snapshotsDir);
console.log('Updated performance baseline');
